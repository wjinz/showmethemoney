/**
 * 특정 날짜의 휴일/기념일 객체를 반환 (없으면 null)
 * @param {string} dateStr 'YYYY-MM-DD' 형태
 * @returns {{name: string, isRed: boolean}|null}
 */
export function getDayInfo(dateStr) {
  if (!dateStr || dateStr.length !== 10) return null;
  const mmdd = dateStr.slice(5, 10);
  
  if (MOVING_HOLIDAYS[dateStr]) {
    return { name: MOVING_HOLIDAYS[dateStr], isRed: true };
  }
  if (FIXED_HOLIDAYS[mmdd]) {
    return { name: FIXED_HOLIDAYS[mmdd], isRed: true };
  }
  if (ANNIVERSARIES[mmdd]) {
    return { name: ANNIVERSARIES[mmdd], isRed: false };
  }
  return null;
}

