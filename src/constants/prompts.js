/**
 * @param {Date} [now]
 * @returns {string}
 */
export function getDailyPrompt(now) {
  const d = now instanceof Date ? now : new Date();
  const idx = ((d.getMonth() * 31) + d.getDate()) % DAILY_PROMPTS.length;
  return DAILY_PROMPTS[idx];
}
